/* Generates supabase/seed/catalog.sql from the bundled course data. Run with: npm run seed:generate */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { languages } from '@/mocks/languages';
import { lessons } from '@/mocks/lessons';
import { levels } from '@/mocks/levels';
import { vocabulary } from '@/mocks/vocabulary';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const out: string[] = ['-- GENERATED by scripts/catalog-seed.gen.ts from src/mocks/*. Do not edit by hand.', 'begin;'];

out.push('insert into public.languages (code,name_ar,name_en,native_name,direction,can_be_source,can_be_target) values');
out.push(languages.map((l) => `(${q(l.code)},${q(l.name.ar)},${q(l.name.en)},${q(l.nativeName)},${q(l.direction)},${l.roles.includes('source')},${l.roles.includes('target')})`).join(',\n') + '\non conflict (code) do update set name_ar=excluded.name_ar,name_en=excluded.name_en,native_name=excluded.native_name,direction=excluded.direction,can_be_source=excluded.can_be_source,can_be_target=excluded.can_be_target;');

out.push('insert into public.levels (id,position,title_ar,title_en) values');
out.push(levels.map((l, i) => `(${q(l.id)},${i + 1},${q(l.title.ar)},${q(l.title.en)})`).join(',\n') + '\non conflict (id) do update set title_ar=excluded.title_ar,title_en=excluded.title_en;');

const targets = languages.filter((l) => l.roles.includes('target'));
out.push('insert into public.courses (language_code,title_ar,title_en) values');
out.push(targets.map((l) => `(${q(l.code)},${q(l.name.ar)},${q(l.name.en)})`).join(',\n') + '\non conflict (language_code) do nothing;');

out.push('insert into public.lessons (id,language_code,level_id,position,title_ar,title_en,summary_ar,summary_en,estimated_minutes) values');
out.push(lessons.map((l) => `(${q(l.id)},${q(l.targetLanguage)},${q(l.levelId)},${l.order},${q(l.title.ar)},${q(l.title.en)},${q(l.summary.ar)},${q(l.summary.en)},${l.estimatedMinutes})`).join(',\n') + '\non conflict (id) do update set title_ar=excluded.title_ar,title_en=excluded.title_en,summary_ar=excluded.summary_ar,summary_en=excluded.summary_en,estimated_minutes=excluded.estimated_minutes;');

const position = new Map<string, number>();
const rows = vocabulary.map((w) => {
  const pos = position.get(w.lessonId) ?? 0;
  position.set(w.lessonId, pos + 1);
  return `(${q(w.id)},${q(w.lessonId)},${q(w.targetLanguage)},${pos},${q(w.term)},${q(JSON.stringify(w.translations))}::jsonb)`;
});
out.push('insert into public.vocabulary (id,lesson_id,language_code,position,term,translations) values');
out.push(rows.join(',\n') + '\non conflict (id) do update set term=excluded.term,translations=excluded.translations;');
out.push('commit;');

it('writes the catalog seed', () => {
  const file = join(__dirname, '..', 'supabase', 'seed', 'catalog.sql');
  writeFileSync(file, out.join('\n') + '\n');
  expect(rows.length).toBe(vocabulary.length);
});
